import { execSync } from 'child_process';
import { CredentialsManager } from './credentials.js';
import type { GitHubRepoMetadata, CreateRepoOptions } from '../types.js';

export interface GitHubApiErrorDetails {
  message: string;
  documentation_url?: string;
  status: number;
}

export class GitHubClient {
  private token: string;
  private apiBase: string;

  constructor(token?: string, apiBase = 'https://api.github.com') {
    this.token = token || CredentialsManager.getGitHubToken();
    this.apiBase = apiBase.replace(/\/+$/, '');
  }

  private getHeaders(): Record<string, string> {
    const headers: Record<string, string> = {
      Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
      'User-Agent': 'SiteForge-Autonomous-Factory/1.0',
    };
    if (this.token) {
      headers.Authorization = `Bearer ${this.token}`;
    }
    return headers;
  }

  /**
   * Get authenticated user profile
   */
  async getAuthenticatedUser(): Promise<{ login: string; id: number; name?: string }> {
    const res = await fetch(`${this.apiBase}/user`, {
      method: 'GET',
      headers: this.getHeaders(),
    });

    if (!res.ok) {
      throw new Error(`Failed to get authenticated user: ${res.status} ${res.statusText}`);
    }

    return (await res.json()) as { login: string; id: number; name?: string };
  }

  /**
   * Check if a repository exists
   */
  async checkRepoExists(owner: string, repo: string): Promise<boolean> {
    try {
      const res = await fetch(`${this.apiBase}/repos/${owner}/${repo}`, {
        method: 'GET',
        headers: this.getHeaders(),
      });
      return res.status === 200;
    } catch {
      return false;
    }
  }

  /**
   * Get repository details
   */
  async getRepo(owner: string, repo: string): Promise<GitHubRepoMetadata | null> {
    const res = await fetch(`${this.apiBase}/repos/${owner}/${repo}`, {
      method: 'GET',
      headers: this.getHeaders(),
    });

    if (res.status === 404) {
      return null;
    }

    if (!res.ok) {
      throw new Error(`Failed to get repo ${owner}/${repo}: ${res.status} ${res.statusText}`);
    }

    const data = (await res.json()) as Record<string, any>;
    return {
      id: data.id,
      name: data.name,
      owner: data.owner?.login || owner,
      fullName: data.full_name,
      htmlUrl: data.html_url,
      cloneUrl: data.clone_url,
      sshUrl: data.ssh_url,
      defaultBranch: data.default_branch || 'main',
      isPrivate: Boolean(data.private),
      description: data.description || '',
      createdAt: data.created_at,
    };
  }

  /**
   * Create a new GitHub repository
   */
  async createRepo(options: CreateRepoOptions): Promise<GitHubRepoMetadata> {
    const currentUsername = CredentialsManager.getAuthenticatedUsername();
    const targetOwner = options.owner || currentUsername;
    const isUserRepo = targetOwner.toLowerCase() === currentUsername.toLowerCase();

    const endpoint = isUserRepo
      ? `${this.apiBase}/user/repos`
      : `${this.apiBase}/orgs/${targetOwner}/repos`;

    const body: Record<string, unknown> = {
      name: options.repoName,
      description: options.description || 'Generated by SiteForge Autonomous Web Factory',
      private: options.isPrivate ?? false,
      auto_init: options.autoInit ?? false,
      has_issues: true,
      has_projects: true,
      has_wiki: false,
    };

    const res = await fetch(endpoint, {
      method: 'POST',
      headers: {
        ...this.getHeaders(),
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(body),
    });

    if (!res.ok) {
      // Fallback via gh CLI if REST endpoint fails (e.g. scope nuances)
      const errText = await res.text();
      try {
        const ghVisibilityFlag = (options.isPrivate ?? false) ? '--private' : '--public';
        const targetSlug = isUserRepo ? options.repoName : `${targetOwner}/${options.repoName}`;
        const descArg = options.description
          ? `--description "${options.description.replace(/"/g, '\\"')}"`
          : '';
        execSync(`gh repo create ${targetSlug} ${ghVisibilityFlag} ${descArg}`, {
          encoding: 'utf-8',
          stdio: ['ignore', 'pipe', 'pipe'],
        });
        const meta = await this.getRepo(targetOwner, options.repoName);
        if (meta) return meta;
      } catch (cliErr: any) {
        throw new Error(
          `Failed to create GitHub repository ${targetOwner}/${options.repoName}: ${res.status} - ${errText} (CLI fallback failed: ${cliErr.message})`
        );
      }
    }

    const data = (await res.json()) as Record<string, any>;
    const metadata: GitHubRepoMetadata = {
      id: data.id,
      name: data.name,
      owner: data.owner?.login || targetOwner,
      fullName: data.full_name,
      htmlUrl: data.html_url,
      cloneUrl: data.clone_url,
      sshUrl: data.ssh_url,
      defaultBranch: data.default_branch || options.defaultBranch || 'main',
      isPrivate: Boolean(data.private),
      description: data.description || '',
      createdAt: data.created_at,
    };

    // Optionally set topics
    if (options.topics && options.topics.length > 0) {
      await this.setTopics(metadata.owner, metadata.name, options.topics);
    }

    return metadata;
  }

  /**
   * Set repository topics
   */
  async setTopics(owner: string, repo: string, topics: string[]): Promise<void> {
    try {
      const sanitizedTopics = topics
        .map((t) => t.toLowerCase().replace(/[^a-z0-9-]/g, '-').slice(0, 35))
        .filter((t) => t.length > 0);

      await fetch(`${this.apiBase}/repos/${owner}/${repo}/topics`, {
        method: 'PUT',
        headers: {
          ...this.getHeaders(),
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({ names: sanitizedTopics }),
      });
    } catch {
      // Non-fatal
    }
  }

  /**
   * Delete a repository (useful for testing and teardown)
   */
  async deleteRepo(owner: string, repo: string): Promise<boolean> {
    try {
      const res = await fetch(`${this.apiBase}/repos/${owner}/${repo}`, {
        method: 'DELETE',
        headers: this.getHeaders(),
      });
      if (res.status === 204) return true;
    } catch {
      // Fallback to gh
    }

    try {
      execSync(`gh repo delete ${owner}/${repo} --yes`, {
        encoding: 'utf-8',
        stdio: ['ignore', 'pipe', 'pipe'],
      });
      return true;
    } catch {
      return false;
    }
  }
}
