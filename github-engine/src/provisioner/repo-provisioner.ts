import { GitHubClient } from '../client/github-client.js';
import { CredentialsManager } from '../client/credentials.js';
import { sanitizeRepoName } from '../sanitizers/repo-name.js';
import type { AnySiteForgePayload, GitHubRepoMetadata, CreateRepoOptions } from '../types.js';

export interface ProvisionRepoParams {
  payload?: AnySiteForgePayload;
  repoName?: string;
  owner?: string;
  isPrivate?: boolean;
  description?: string;
  defaultBranch?: string;
  topics?: string[];
}

export class RepoProvisioner {
  private client: GitHubClient;

  constructor(client?: GitHubClient) {
    this.client = client || new GitHubClient();
  }

  /**
   * Provisions a GitHub repository from payload metadata or explicit parameters
   */
  async provisionRepository(params: ProvisionRepoParams): Promise<GitHubRepoMetadata> {
    const payload = params.payload as any;

    // 1. Resolve raw repository name
    const rawRepoName =
      params.repoName ||
      payload?.integrations?.github?.repoName ||
      payload?.theme?.name ||
      'siteforge-angular-app';

    // 2. Sanitize repository name to strictly adhere to GitHub requirements
    const sanitizedName = sanitizeRepoName(rawRepoName);

    // 3. Resolve target owner
    const authenticatedUser = CredentialsManager.getAuthenticatedUsername();
    let targetOwner = params.owner || payload?.integrations?.github?.owner || authenticatedUser;

    // 4. Resolve visibility
    const isPrivate =
      params.isPrivate !== undefined
        ? params.isPrivate
        : payload?.integrations?.github?.isPrivate ?? false;

    // 5. Resolve description
    const description =
      params.description ||
      payload?.integrations?.github?.description ||
      (payload?.theme?.description
        ? `${payload.theme.description} — Generated by SiteForge Autonomous Web Factory`
        : 'Generated by SiteForge Autonomous Angular Web Factory');

    // 6. Resolve topics
    const defaultTopics = ['siteforge', 'angular', 'zoneless', 'signals'];
    if (payload?.siteType) defaultTopics.push(payload.siteType);
    if (payload?.designPreset) defaultTopics.push(payload.designPreset);
    if (payload?.integrations?.github?.topics) {
      defaultTopics.push(...payload.integrations.github.topics);
    }
    const topics = Array.from(new Set([...defaultTopics, ...(params.topics || [])]));

    // 7. Check if repository already exists under target owner or authenticated user
    let existingRepo = await this.client.getRepo(targetOwner, sanitizedName);
    if (!existingRepo && targetOwner !== authenticatedUser) {
      // Check under authenticated user
      existingRepo = await this.client.getRepo(authenticatedUser, sanitizedName);
      if (existingRepo) {
        targetOwner = authenticatedUser;
      }
    }

    if (existingRepo) {
      return existingRepo;
    }

    // 8. Create new repository
    const createOptions: CreateRepoOptions = {
      repoName: sanitizedName,
      owner: targetOwner,
      description,
      isPrivate,
      autoInit: false,
      defaultBranch: params.defaultBranch || payload?.integrations?.github?.defaultBranch || 'main',
      topics,
    };

    return await this.client.createRepo(createOptions);
  }
}
