import type { AnySiteForgePayload } from '../types.js';

export interface FormattedCommitMessage {
  summary: string;
  body: string;
  fullMessage: string;
}

export class CommitFormatter {
  /**
   * Formats a clean, conventional commit message for the factory-generated project
   */
  static formatInitialCommit(
    payload: AnySiteForgePayload,
    stats: { filesCount: number; projectName?: string }
  ): FormattedCommitMessage {
    const siteType = payload.siteType;
    const designPreset = payload.designPreset;
    const projectName =
      stats.projectName ||
      payload.integrations?.github?.repoName ||
      payload.theme?.name ||
      'siteforge-app';

    const summary = `feat(factory): initial hydrate ${projectName} [${siteType}/${designPreset}]`;

    const bodyLines = [
      `SiteForge Autonomous Web Factory - Initial Codebase Hydration`,
      ``,
      `Core Architecture & Stack:`,
      `• Framework: Modern Angular 19+ (100% Standalone, 0% NgModules)`,
      `• Reactivity: Signals-first (signal, computed, input, output, model)`,
      `• Performance: Zoneless Change Detection (provideZonelessChangeDetection)`,
      `• Styling: Compiled Design.md Tokens (${designPreset} profile)`,
      `• Archetype: ${siteType}`,
      `• Domain Subject: ${payload.theme?.topic || payload.theme?.name || 'N/A'}`,
      `• Tagline: "${payload.theme?.tagline || 'Crafted by SiteForge'}"`,
      `• Hydrated Files: ${stats.filesCount} project files`,
      ``,
      `Generated by SiteForge Autonomous Web Factory Engine`,
    ];

    const body = bodyLines.join('\n');
    const fullMessage = `${summary}\n\n${body}`;

    return {
      summary,
      body,
      fullMessage,
    };
  }
}
