import * as fs from 'fs';
import * as path from 'path';
import { TokenCompiler } from '../compiler/token-compiler.js';
import { ArchetypeTemplates, SiteType } from '../templates/archetype-templates.js';
import { WorkspaceTemplates } from '../templates/workspace-templates.js';
import { DesignPresetName } from '../presets/design-presets.js';

export interface SiteForgePayloadInput {
  version: '1.0.0';
  siteType: SiteType;
  designPreset: DesignPresetName;
  theme: {
    topic: string;
    name: string;
    tagline: string;
    description: string;
    branding?: {
      primaryColor?: string;
      secondaryColor?: string;
      fontHeading?: string;
      fontBody?: string;
    };
    content?: Record<string, unknown>;
  };
  integrations: {
    github: {
      repoName: string;
      isPrivate?: boolean;
    };
    vercel: {
      projectName: string;
    };
  };
}

export interface GenerationResult {
  success: boolean;
  targetDir: string;
  projectName: string;
  siteType: SiteType;
  designPreset: DesignPresetName;
  filesGenerated: string[];
}

export class ProjectGenerator {
  /**
   * Validate the JSON payload against SiteForge rules
   */
  static validatePayload(payload: unknown): { valid: boolean; errors: string[] } {
    const errors: string[] = [];
    if (!payload || typeof payload !== 'object') {
      return { valid: false, errors: ['Payload must be a non-null object'] };
    }

    const p = payload as Record<string, unknown>;
    if (p['version'] !== '1.0.0') {
      errors.push('version must be "1.0.0"');
    }

    const validSiteTypes: SiteType[] = [
      'learning_platform',
      'blog',
      'newsletter',
      'ecommerce',
      'social_media',
      'landing_page',
    ];
    if (!validSiteTypes.includes(p['siteType'] as SiteType)) {
      errors.push(`siteType must be one of: ${validSiteTypes.join(', ')}`);
    }

    const validPresets: DesignPresetName[] = [
      'warm-organic',
      'neo-brutalist',
      'clean-editorial',
      'modern-saas-dark',
      'corporate-enterprise',
    ];
    if (!validPresets.includes(p['designPreset'] as DesignPresetName)) {
      errors.push(`designPreset must be one of: ${validPresets.join(', ')}`);
    }

    if (!p['theme'] || typeof p['theme'] !== 'object') {
      errors.push('theme is required and must be an object');
    } else {
      const theme = p['theme'] as Record<string, unknown>;
      if (!theme['name']) errors.push('theme.name is required');
      if (!theme['topic']) errors.push('theme.topic is required');
      if (!theme['tagline']) errors.push('theme.tagline is required');
      if (!theme['description']) errors.push('theme.description is required');
    }

    if (!p['integrations'] || typeof p['integrations'] !== 'object') {
      errors.push('integrations is required');
    }

    return { valid: errors.length === 0, errors };
  }

  /**
   * Generates a complete Angular 19+ standalone application workspace
   */
  static generateProject(
    payload: SiteForgePayloadInput,
    outputDirectory: string
  ): GenerationResult {
    const validation = this.validatePayload(payload);
    if (!validation.valid) {
      throw new Error(`Invalid SiteForge Payload: ${validation.errors.join('; ')}`);
    }

    const projectName =
      payload.integrations.github.repoName ||
      payload.theme.name.toLowerCase().replace(/[^a-z0-9]/g, '-');

    const projectRoot = path.resolve(outputDirectory);
    const srcDir = path.join(projectRoot, 'src');
    const appDir = path.join(srcDir, 'app');

    // Ensure directories exist
    fs.mkdirSync(appDir, { recursive: true });

    const filesGenerated: string[] = [];

    const writeFile = (relPath: string, content: string) => {
      const fullPath = path.join(projectRoot, relPath);
      fs.mkdirSync(path.dirname(fullPath), { recursive: true });
      fs.writeFileSync(fullPath, content, 'utf-8');
      filesGenerated.push(relPath);
    };

    // 1. Root Configuration files
    writeFile('package.json', WorkspaceTemplates.getPackageJson(projectName));
    writeFile('angular.json', WorkspaceTemplates.getAngularJson(projectName));
    writeFile('tsconfig.json', WorkspaceTemplates.getTsConfig());
    writeFile('tsconfig.app.json', WorkspaceTemplates.getTsConfigApp());
    writeFile('README.md', `# ${payload.theme.name}\n\nGenerated by SiteForge Autonomous Angular Web Factory.\nArchetype: \`${payload.siteType}\` • Preset: \`${payload.designPreset}\`\n\n## Development\n\`\`\`bash\nnpm install\nnpm start\n\`\`\`\n`);
    writeFile('vercel.json', WorkspaceTemplates.getVercelJson(projectName));

    // 2. Compile Design.md Tokens
    const compiledCss = TokenCompiler.compilePresetToCss(
      payload.designPreset,
      payload.theme.branding
    );
    writeFile('src/design-tokens.css', compiledCss);
    writeFile('src/styles.css', WorkspaceTemplates.getStylesCss());

    // 3. Application Entrypoints
    writeFile('src/main.ts', WorkspaceTemplates.getMainTs());
    writeFile(
      'src/index.html',
      WorkspaceTemplates.getIndexHtml(payload.theme.name, payload.theme.description)
    );

    // 4. App Core & Root Component
    writeFile('src/app/app.config.ts', WorkspaceTemplates.getAppConfig());
    writeFile('src/app/app.routes.ts', WorkspaceTemplates.getAppRoutes());
    writeFile('src/app/app.ts', WorkspaceTemplates.getAppTs(payload.theme.name));

    // 5. Archetype View Component
    const archetypeComponent = ArchetypeTemplates.getArchetypeComponent(payload.siteType, {
      siteType: payload.siteType,
      title: payload.theme.name,
      tagline: payload.theme.tagline,
      description: payload.theme.description,
      content: payload.theme.content,
    });
    writeFile('src/app/archetype-view.component.ts', archetypeComponent);

    return {
      success: true,
      targetDir: projectRoot,
      projectName,
      siteType: payload.siteType,
      designPreset: payload.designPreset,
      filesGenerated,
    };
  }
}
